#!/bin/bash
# GoldataWeb2 operations on Synology DSM 7.1 (Docker package, docker-compose v1). Run as root from the project folder:
#   cd /volume1/docker/goldata && sudo ./goldata.sh <command>          (prod; UAT: /volume1/docker/goldata-uat)
# Commands: pull | migrate | import-users <login.php> | up | down | status | logs [svc] | check | backup-db [dir]
#           | php-config | upgrade <tag> | rollback | env
# All settings come from the ONE env file of this environment: ./.env (deploy/env/{prod,uat}.env.example).
# See deploy/DEPLOYMENT.md. Keep this script and the runbook in sync.
set -euo pipefail

cd "$(dirname "$(readlink -f "$0")")"
ENV_FILE=.env
[ -f "$ENV_FILE" ] || { echo "Missing $ENV_FILE (copy deploy/env/prod.env.example or uat.env.example)"; exit 2; }

# Read KEY=value lines literally (no shell expansion, so '$' in a password is safe), like docker-compose does.
load_env() {
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    case "$line" in ''|'#'*) continue ;; esac
    key="${line%%=*}"; val="${line#*=}"
    [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
    export "$key=$val"
  done < "$ENV_FILE"
}
load_env

perm=$(stat -c '%a' "$ENV_FILE" 2>/dev/null || echo 600)
[ "$perm" = "600" ] || echo "WARNING: $ENV_FILE holds secrets — run: chown root:root $ENV_FILE && chmod 600 $ENV_FILE" >&2

if command -v docker-compose >/dev/null 2>&1; then DC=(docker-compose); else DC=(docker compose); fi
dc() { "${DC[@]}" "$@"; }

health_url="http://127.0.0.1:${WEB_PORT:-8085}/health/ready"

notify() {   # DSM notification (bell + e-mail if configured), falls back to stderr
  if [ -x /usr/syno/bin/synodsmnotify ]; then /usr/syno/bin/synodsmnotify @administrators "GoldataWeb2 ${GOLDATA_ENV:-}" "$1" || true; fi
  echo "$1" >&2
}

wait_healthy() {
  local tries=${1:-40}
  for _ in $(seq "$tries"); do
    if curl -fsS -m 5 "$health_url" >/dev/null 2>&1; then echo "Healthy: $health_url"; return 0; fi
    sleep 3
  done
  echo "NOT healthy after $((tries * 3)) s: $health_url"; curl -sS -m 5 "$health_url" || true; echo
  return 1
}

set_tags() {
  sed -i -E "s/^API_TAG=.*/API_TAG=$1/; s/^WEB_TAG=.*/WEB_TAG=$1/" "$ENV_FILE"
}

# PHP single-quoted literal: escape \ then '
php_quote() { local bs='\' q="'" v=$1; v=${v//"$bs"/"$bs$bs"}; v=${v//"$q"/"$bs$q"}; printf "'%s'" "$v"; }

cmd=${1:-help}; shift || true
case "$cmd" in
  env)     echo "GOLDATA_ENV=${GOLDATA_ENV:-?} project=${COMPOSE_PROJECT_NAME:-?} db=${DB_LEGACY_NAME:-?}/${DB_APP_NAME:-?} port=${WEB_PORT:-?} subnet=${NETWORK_SUBNET:-?} docs=${DOC_ROOT:-?}" ;;
  pull)    dc pull ;;
  migrate) dc run --rm --no-deps api --migrate ;;
  import-users)
    file=${1:?usage: import-users /path/to/login.php}
    dir=$(cd "$(dirname "$file")" && pwd)
    dc run --rm --no-deps -v "$dir:/import:ro" api --import-users "/import/$(basename "$file")"
    ;;
  up)      mkdir -p data/keys data/logs && chown -R "${DOC_UID}:${DOC_GID}" data && dc up -d && wait_healthy ;;
  down)    dc down ;;
  status)  dc ps ;;
  logs)    dc logs --tail=200 "$@" ;;
  check)
    # Task Scheduler, every 5 min: notify after 3 consecutive failures (counter in data/).
    counter=data/.health-failures
    if curl -fsS -m 10 "$health_url" >/dev/null 2>&1; then
      [ -f "$counter" ] && [ "$(cat "$counter")" -ge 3 ] && notify "已恢复正常 ($health_url)"
      echo 0 > "$counter"
    else
      n=$(( $(cat "$counter" 2>/dev/null || echo 0) + 1 )); echo "$n" > "$counter"
      [ "$n" -eq 3 ] && notify "健康检查连续 3 次失败：$health_url — 请查看 docker-compose logs"
      exit 1
    fi
    ;;
  backup-db)
    target=${1:-${BACKUP_DIR:?set BACKUP_DIR in .env or pass a folder}}
    mkdir -p "$target"
    stamp=$(date +%Y%m%d-%H%M)
    # Credentials from .env, handed to mysqldump in a temporary root-only option file (not on the command line).
    cnf=$(umask 077; mktemp)
    trap 'rm -f "$cnf"' EXIT
    printf '[client]\nuser=%s\npassword=%s\n' "${DB_BACKUP_USER:?}" "${DB_BACKUP_PASSWORD:?}" > "$cnf"
    for db in "${DB_LEGACY_NAME:?}" "${DB_APP_NAME:?}"; do
      "${MARIADB_BIN}/mysqldump" --defaults-extra-file="$cnf" -h "${BACKUP_DB_HOST:-127.0.0.1}" -P "${DB_PORT:-3307}" \
        --single-transaction --routines --triggers --default-character-set=utf8mb4 "$db" | gzip > "$target/${db}-${stamp}.sql.gz"
    done
    find "$target" -name '*.sql.gz' -mtime +"${BACKUP_KEEP_DAYS:-30}" -delete
    echo "Backup written to $target"
    ;;
  php-config)
    # Writes the PHP login-bridge config (legacy-php/overlay/app_auth.php) from this env file: one source of truth.
    out=${PHP_AUTH_CONFIG:?set PHP_AUTH_CONFIG in .env}
    mkdir -p "$(dirname "$out")"
    ( umask 077
      { echo "<?php"
        echo "// GENERATED by goldata.sh php-config from $(pwd)/$ENV_FILE ($(date +%F)). Do not edit: change .env and re-run."
        echo "return ["
        echo "    'host' => $(php_quote "${PHP_AUTH_DB_HOST:-127.0.0.1}"),"
        echo "    'port' => ${DB_PORT:-3307},"
        echo "    'db' => $(php_quote "${DB_APP_NAME:?}"),"
        echo "    'user' => $(php_quote "${DB_PHP_AUTH_USER:?}"),"
        echo "    'pass' => $(php_quote "${DB_PHP_AUTH_PASSWORD:?}"),"
        echo "    'public_url' => $(php_quote "${PUBLIC_BASE_URL:-}"),"
        echo "];"
      } > "$out" )
    chown http:http "$out" 2>/dev/null || echo "WARNING: could not chown $out to http" >&2
    chmod 600 "$out"
    echo "Wrote $out"
    ;;
  upgrade)
    tag=${1:?usage: upgrade <version-tag>}
    cp -p "$ENV_FILE" .env.prev
    set_tags "$tag"
    load_env
    dc pull
    dc run --rm --no-deps api --migrate
    dc up -d
    if ! wait_healthy; then notify "升级到 $tag 后健康检查失败。回滚：sudo ./goldata.sh rollback"; exit 1; fi
    echo "Upgraded to $tag (previous settings in .env.prev)"
    ;;
  rollback)
    [ -f .env.prev ] || { echo "No .env.prev"; exit 2; }
    cp -p "$ENV_FILE" .env.failed && cp -p .env.prev "$ENV_FILE"
    load_env
    dc up -d && wait_healthy
    echo "Rolled back to API_TAG=${API_TAG} WEB_TAG=${WEB_TAG}. DB migrations are forward-only and were not reversed."
    ;;
  *)
    sed -n '2,7p' "$0"; exit 2 ;;
esac
